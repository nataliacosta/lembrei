process.env.TZ = "America/Sao_Paulo";
import functionsTest from "firebase-functions-test";
const ft = functionsTest({ projectId: "demo-lembrei" });
const webpush = (await import("web-push")).default;
const recebidos = [];
webpush.sendNotification = async (sub, payload) => { recebidos.push(JSON.parse(payload)); return { statusCode: 201 }; };
const { lembretesAgendados } = await import("../lib/index.js");
const { getFirestore, Timestamp } = await import("firebase-admin/firestore");
const db = getFirestore();
const agora = new Date();
const hhmm = (d) => d.toTimeString().slice(0, 5);
const hoje = new Date(agora); hoje.setHours(0, 0, 0, 0);
const ontem = new Date(hoje); ontem.setDate(ontem.getDate() - 1);
const ana = db.collection("usuarios").doc("ana");
await ana.set({ nome: "Ana", prefsNotificacoes: { resumo: { ativo: true, hora: hhmm(new Date(agora - 2 * 60000)), dias: [0, 1, 2, 3, 4, 5, 6] }, reunioes: { ativo: true, minutosAntes: 15 } } });
await ana.collection("dispositivos").doc("ok").set({ endpoint: "https://push.exemplo/ok", keys: { p256dh: "x", auth: "y" }, nome: "Chrome" });
const bruno = db.collection("usuarios").doc("bruno"); // sem aparelho: não recebe nada
await bruno.set({ nome: "Bruno" });
const frente = db.collection("frentes").doc("f");
const base = { concluido: false, membrosUids: ["ana"], criadoPor: "ana", responsavelId: "ana", frenteId: "f", tags: [] };
await frente.collection("itens").doc("atrasada").set({ ...base, tipo: "tarefa", titulo: "Atrasada", prazo: Timestamp.fromDate(ontem) });
const daqui10 = new Date(agora.getTime() + 10 * 60000);
await frente.collection("itens").doc("reuniao").set({ ...base, tipo: "reuniao", titulo: "Comitê de TI", prazo: null, reuniao: { frequencia: "semanal", inicio: Timestamp.fromDate(hoje), hora: hhmm(daqui10), sala: "Sala Ipê", preparos: [{ id: "p1", titulo: "Pauta", diasAntes: 0 }], feitos: {}, puladas: [] } });
await frente.collection("itens").doc("reuniao-outra").set({ ...base, tipo: "reuniao", titulo: "Reunião do Bruno", responsavelId: "bruno", prazo: null, reuniao: { frequencia: "semanal", inicio: Timestamp.fromDate(hoje), hora: hhmm(daqui10), preparos: [], feitos: {}, puladas: [] } });
let falhas = 0;
const conferir = (nome, cond, extra = "") => { if (!cond) falhas++; console.log(cond ? "  ✔" : "  ✘", nome, cond ? "" : extra); };
const rodar = () => ft.wrap(lembretesAgendados)({});
await rodar();
const resumo = recebidos.find((r) => r.tag?.startsWith("resumo-"));
const reuniao = recebidos.find((r) => r.tag?.startsWith("reuniao-"));
conferir("resumo diário enviado", resumo && resumo.body.includes("1 atrasado") && resumo.link === "/dashboard", JSON.stringify(recebidos));
conferir("resumo cita a reunião de hoje", resumo?.body.includes("Comitê de TI"), resumo?.body);
conferir("lembrete da reunião (só a da Ana)", reuniao && /^Reunião em (9|10) min$/.test(reuniao.title) && reuniao.body.startsWith("Comitê de TI às") && reuniao.body.includes(" · Sala Ipê · 0 de 1 preparo feito"), JSON.stringify(reuniao));
conferir("reunião em que ela não é responsável não avisa", !recebidos.some((r) => r.body?.includes("Reunião do Bruno") && r.tag?.startsWith("reuniao-")));
conferir("só 2 avisos no total", recebidos.length === 2, String(recebidos.length));
await rodar();
conferir("rodar de novo não repete nada", recebidos.length === 2, String(recebidos.length));
await ana.set({ prefsNotificacoes: { resumo: { ativo: false }, reunioes: { ativo: false } }, ultimoResumo: null }, { merge: true });
await rodar();
conferir("com tudo desligado, nada é enviado", recebidos.length === 2, String(recebidos.length));
console.log(falhas ? `${falhas} falha(s)` : "tudo ok"); process.exit(falhas ? 1 : 0);
